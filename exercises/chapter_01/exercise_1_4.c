#include <stdio.h>

int main(void) {
    printf("习题1.4：计算并输出\n");
    printf("========================\n\n");
    
    int a = 10;
    int b = 3;
    
    printf("a = %d, b = %d\n", a, b);
    printf("加法：a + b = %d\n", a + b);
    printf("减法：a - b = %d\n", a - b);
    printf("乘法：a * b = %d\n", a * b);
    printf("除法：a / b = %d\n", a / b);
    printf("取模：a %% b = %d\n", a % b);
    
    return 0;
}
